import pg from 'pg';
import { FieldSpec, newId, type FilterCondition, type FilterGroup } from '@riosoma/contracts';
import { ident, join, migrate, query, sql, type Sql } from '@riosoma/db';
import { startTestPostgres } from '@riosoma/testkit';
import { MIGRATIONS } from '../../migrations/index.js';
import type { ReadContext, StoredField } from '../types.js';
import { columnType, typeSql } from './columns.js';

export const ctx: ReadContext = {
  now: new Date('2024-01-31T10:30:00Z'),
  timeZone: 'UTC',
  natural: true,
};
export const schemas = { app: 'order_app', data: 'order_data', audit: 'order_audit' };
export const choiceIds = ['cho00000000000001', 'cho00000000000002', 'cho00000000000003'];
export const userIds = ['usr00000000000001', 'usr00000000000002', 'usr00000000000003'];

export function field(type: StoredField['type'], options: unknown = {}): StoredField {
  const id = newId('field');
  return {
    ...FieldSpec.parse({ type, options }),
    id,
    columnName: `col_${id}`,
    tableId: newId('table'),
    name: type,
    description: '',
    position: 0,
    createdAt: ctx.now.toISOString(),
    updatedAt: ctx.now.toISOString(),
  };
}

export function condition(
  f: StoredField,
  operator: FilterCondition['operator'],
  value?: unknown,
): FilterCondition {
  return { id: 'condition', fieldId: f.id, operator, value };
}

export function group(...conditions: FilterGroup['conditions']): FilterGroup {
  return { conjunction: 'and', conditions };
}

export async function fixture() {
  const kit = await startTestPostgres();
  const database = await kit.createDatabase('order');
  const pool = new pg.Pool({ connectionString: database.url });
  // Dropping the database at the end can reach a connection that's still closing; that's expected.
  pool.on('error', () => {});
  await migrate(pool, schemas, MIGRATIONS);
  const orgId = newId('org');
  const databaseId = newId('database');
  await query(pool, sql`INSERT INTO ${ident(schemas.app, 'orgs')} (id, name) VALUES (${orgId}, ${'Tests'})`);
  await query(
    pool,
    sql`INSERT INTO ${ident(schemas.app, 'databases')} (id, org_id, name)
    VALUES (${databaseId}, ${orgId}, ${'Tests'})`,
  );
  for (const [i, id] of userIds.entries()) {
    await query(
      pool,
      sql`INSERT INTO ${ident(schemas.app, 'users')} (id, email, name)
      VALUES (${id}, ${`${id}@example.com`}, ${['Zoe', 'Amy', ''][i]})`,
    );
  }
  return {
    pool,
    url: database.url,
    async table(fields: StoredField[] = []) {
      const tableId = newId('table');
      await query(
        pool,
        sql`INSERT INTO ${ident(schemas.app, 'tables')}
        (id, org_id, database_id, name, primary_field_id, position)
        VALUES (${tableId}, ${orgId}, ${databaseId}, ${tableId}, ${fields[0]?.id ?? newId('field')}, ${0})`,
      );
      const columns: Sql[] = [
        sql`
        __rid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        __id text NOT NULL UNIQUE,
        __created_at timestamptz, __created_by text,
        __updated_at timestamptz, __updated_by text, __deleted_at timestamptz,
        __source_gone boolean NOT NULL DEFAULT false`,
      ];
      for (const f of fields) {
        const type = columnType(f);
        if (type) columns.push(sql`${ident(f.columnName)} ${typeSql(type)}`);
      }
      await query(pool, sql`CREATE TABLE ${ident(schemas.data, tableId)} (${join(columns, ', ')})`);
      return tableId;
    },
    async close() {
      await pool.end();
      await database.drop();
      await kit.stop();
    },
  };
}

export type Fixture = Awaited<ReturnType<typeof fixture>>;
