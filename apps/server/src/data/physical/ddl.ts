import { buildUniqueIndex } from './unique.js';
import { ident, join, query, sql, type Queryable } from '@riosoma/db';
import type { StoredField } from '../types.js';
import { initializeAutoNumber } from './autonumber.js';
import { columnType, typeSql } from './columns.js';

export async function createRecordTable(
  db: Queryable,
  dataSchema: string,
  tableId: string,
  fields: readonly StoredField[],
): Promise<void> {
  const columns = fields.flatMap((field) => {
    const type = columnType(field);
    return type ? [sql`${ident(field.columnName)} ${typeSql(type)}`] : [];
  });
  await query(
    db,
    sql`CREATE TABLE ${ident(dataSchema, tableId)} (
    ${join(
      [
        sql`__rid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`,
        sql`__id text NOT NULL UNIQUE`,
        sql`__created_at timestamptz NOT NULL DEFAULT now()`,
        sql`__created_by text`,
        sql`__updated_at timestamptz NOT NULL DEFAULT now()`,
        sql`__updated_by text`,
        sql`__deleted_at timestamptz`,
        sql`__trashed_by text`,
        sql`__source_gone boolean NOT NULL DEFAULT false`,
        sql`__overrides jsonb`,
        ...columns,
      ],
      ', ',
    )}
  )`,
  );
  await query(
    db,
    sql`CREATE INDEX ${ident(`${tableId}_trash`)} ON ${ident(dataSchema, tableId)}
    (__deleted_at DESC, __id DESC) WHERE __deleted_at IS NOT NULL`,
  );
  for (const field of fields) {
    if (field.type === 'autoNumber') await initializeAutoNumber(db, dataSchema, field);
    await buildUniqueIndex(db, { data: dataSchema }, field, false);
  }
}

/** Only source tables need to maintain choice identities on record writes. */
export async function ensureSourceChoiceIndex(
  db: Queryable,
  dataSchema: string,
  tableId: string,
): Promise<void> {
  await query(
    db,
    sql`CREATE INDEX IF NOT EXISTS ${ident(`${tableId}_choice`)} ON ${ident(dataSchema, tableId)}
    (${ident(dataSchema, 'source_choice_id')}(__id))`,
  );
}

export async function addFieldColumn(
  db: Queryable,
  dataSchema: string,
  tableId: string,
  field: StoredField,
): Promise<void> {
  const type = columnType(field);
  if (type) {
    await query(
      db,
      sql`ALTER TABLE ${ident(dataSchema, tableId)}
      ADD COLUMN ${ident(field.columnName)} ${typeSql(type)}`,
    );
    if (field.type === 'autoNumber') await initializeAutoNumber(db, dataSchema, field);
    await buildUniqueIndex(db, { data: dataSchema }, field, false);
  }
}

export async function dropRecordTable(db: Queryable, dataSchema: string, tableId: string): Promise<void> {
  await query(db, sql`DROP TABLE ${ident(dataSchema, tableId)}`);
}

export async function dropColumn(
  db: Queryable,
  dataSchema: string,
  tableId: string,
  columnName: string,
): Promise<void> {
  await query(db, sql`ALTER TABLE ${ident(dataSchema, tableId)} DROP COLUMN ${ident(columnName)}`);
}
