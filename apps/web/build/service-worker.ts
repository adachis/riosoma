import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import type { Plugin } from 'vite';

/**
 * Writes the app's service worker (`sw.js`) and web app manifest (`manifest.webmanifest`) into a
 * production build.  The worker itself is `service-worker-runtime.js`, and this step only gives it the
 * build's file list and routing settings.
 */

export const MANIFEST_FILE = 'manifest.webmanifest';
export const WORKER_FILE = 'sw.js';

export interface PrecacheEntry {
  url: string;
  /** Null for files whose names already change with their contents. */
  revision: string | null;
}

export interface WorkerOptions {
  /** Scripts the worker imports before its own routes, so their fetch listeners answer first. */
  importScripts: string[];
  /** The web app manifest, written as is. */
  manifest: Record<string, unknown>;
  /**
   * The built files to precache, relative to the output directory.  It runs after every file is
   * written, and the manifest is added to the list afterward.
   */
  precache: (output: string) => string[];
  navigateFallback: string;
  navigateFallbackDenylist: RegExp[];
}

/** Built files the worker may precache, matching the app shell's top-level files and folders. */
export const PRECACHE_CANDIDATES = [
  /^index\.html$/,
  /^boot\.js$/,
  /^layers\.css$/,
  /^pressable\.css$/,
  // The recovery script runs inline in index.html, so only its stylesheet is a separate shell file.
  /^startup-recovery\.css$/,
  /^assets\/[^/]+\.(?:js|css)$/,
  /^icons\/[^/]+\.(?:svg|png)$/,
  /^brand\/riosoma-wordmark-mask\.svg$/,
];

/**
 * The candidates the worker precaches: the measured shell and recovery files (`common`) and every
 * icon.  Locale and feature chunks stay out, so they are cached only once someone requests them.
 */
export function selectPrecache(files: string[], common: Set<string>): string[] {
  return files.filter(
    (file) =>
      PRECACHE_CANDIDATES.some((pattern) => pattern.test(file)) &&
      (common.has(file) || file.startsWith('icons/')),
  );
}

/** Every file in a directory, relative to it and with forward slashes, in a stable order. */
export function listFiles(directory: string): string[] {
  return readdirSync(directory, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(directory, join(entry.parentPath, entry.name)).split(sep).join('/'))
    .sort();
}

/**
 * Build assets carry a content hash in their names, so their address alone identifies a version.
 * Every other file is keyed by a hash of its contents, so a new build replaces a changed file.
 */
export function revisioned(files: string[], read: (file: string) => Buffer): PrecacheEntry[] {
  return [...new Set(files)].map((url) => ({
    url,
    revision: url.startsWith('assets/') ? null : createHash('md5').update(read(url)).digest('hex'),
  }));
}

/** The generated worker: listener imports, its settings, and then the runtime source. */
export function workerScript(
  settings: Pick<WorkerOptions, 'importScripts' | 'navigateFallback' | 'navigateFallbackDenylist'> & {
    precache: PrecacheEntry[];
  },
  runtime: string,
  scripts: (address: string) => string,
): string {
  // Entries are written as plain object literals, one per file, so a test can find a file's entry.
  const precache = settings.precache
    .map((entry) => `{url:${JSON.stringify(entry.url)},revision:${JSON.stringify(entry.revision)}}`)
    .join(',');
  return [
    '// Generated by apps/web/build/service-worker.ts from service-worker-runtime.js.',
    // Inline shipped listeners so classic workers never need an untyped importScripts sink.
    ...settings.importScripts.map((script) => `(() => {\n${scripts(script)}\n})();`),
    'self.rioWorker = {',
    "  cacheName: 'rio-precache-v1-' + self.registration.scope,",
    `  precache: [${precache}],`,
    `  navigationFallback: ${JSON.stringify(settings.navigateFallback)},`,
    `  navigationDenylist: [${settings.navigateFallbackDenylist.map(String).join(', ')}],`,
    '};',
    runtime,
  ].join('\n');
}

/** Links the manifest from the page head, which is how browsers find an installable app. */
export function linkManifest(html: string): string {
  return html.replace('</head>', `<link rel="manifest" href="/${MANIFEST_FILE}"></head>`);
}

export function serviceWorker(options: WorkerOptions): Plugin {
  let output = '';
  let written = false;
  return {
    name: 'web-service-worker',
    apply: 'build',
    configResolved(config) {
      output = resolve(config.root, config.build.outDir);
    },
    transformIndexHtml: { order: 'post', handler: linkManifest },
    generateBundle() {
      this.emitFile({
        type: 'asset',
        fileName: MANIFEST_FILE,
        source: `${JSON.stringify(options.manifest)}\n`,
      });
    },
    writeBundle() {
      written = true;
    },
    // The file list needs the finished output: the build manifest, public files, and final page.
    closeBundle: {
      order: 'post',
      sequential: true,
      handler() {
        if (!written) return;
        const precache = revisioned([...options.precache(output), MANIFEST_FILE], (file) =>
          readFileSync(resolve(output, file)),
        );
        const runtime = readFileSync(resolve(import.meta.dirname, 'service-worker-runtime.js'), 'utf8');
        writeFileSync(
          resolve(output, WORKER_FILE),
          workerScript({ ...options, precache }, runtime, (address) =>
            readFileSync(resolve(output, address.replace(/^\//, '')), 'utf8'),
          ),
        );
      },
    },
  };
}
