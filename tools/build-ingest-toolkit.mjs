import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = new URL('../', import.meta.url);
const exports = [];
const chunks = ['source', 'cleaners', 'tables'].map((name) => {
  const filename = new URL(`packages/ingest/src/${name}.ts`, root);
  const source = ts.createSourceFile(name, readFileSync(filename, 'utf8'), ts.ScriptTarget.ES2023, true);
  const statements = source.statements.filter((statement) => {
    if (ts.isImportDeclaration(statement)) {
      if (!statement.moduleSpecifier.text.startsWith('./')) throw new Error('ingest.toolkit.externalImport');
      return false;
    }
    if (statement.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)) {
      if (ts.isFunctionDeclaration(statement)) exports.push(statement.name.text);
      if (ts.isVariableStatement(statement))
        exports.push(...statement.declarationList.declarations.map((declaration) => declaration.name.getText(source)));
    }
    return true;
  });
  const printer = ts.createPrinter();
  const text = statements.map((statement) => printer.printNode(ts.EmitHint.Unspecified, statement, source)).join('\n');
  return ts.transpileModule(text, {
    compilerOptions: { target: ts.ScriptTarget.ES2023, module: ts.ModuleKind.ESNext, removeComments: true },
  }).outputText.replace(/^export /gmu, '').replace(/^export \{\};?\s*$/gmu, '');
});
const version = `1-${createHash('sha256').update(chunks.join('\n')).digest('hex').slice(0, 16)}`;
const script = `(() => {\n${chunks.join('\n')}\nconst api = { ${exports.join(', ')}, version: ${JSON.stringify(version)} }\nfor (const value of Object.values(api)) { if (value && (typeof value === 'object' || typeof value === 'function')) Object.freeze(value) }\nObject.setPrototypeOf(api, null)\nObject.defineProperty(globalThis, 'ingest', { value: Object.freeze(api), writable: false, configurable: false })\n})()`;
const output = `// Generated by tools/build-ingest-toolkit.mjs so readers load only portable helpers.\nexport const TOOLKIT_VERSION = ${JSON.stringify(version)};\nexport const TOOLKIT_SCRIPT = ${JSON.stringify(script)};\n`;
const destination = new URL('apps/server/src/ingest/readers/toolkit-bundle.ts', root);
if (process.argv.includes('--check')) {
  // Formatting may wrap declarations, so compare the values rather than their whitespace.
  const current = ts.createSourceFile('bundle.ts', readFileSync(destination, 'utf8'), ts.ScriptTarget.Latest, true);
  const values = current.statements.flatMap((statement) => ts.isVariableStatement(statement)
    ? statement.declarationList.declarations.map((declaration) => declaration.initializer?.text) : []);
  if (values[0] !== version || values[1] !== script) throw new Error('ingest.toolkit.staleBundle');
} else writeFileSync(fileURLToPath(destination), output);
